#!/usr/bin/env python3
"""
Usage
-----
    python run_atomics.py --list                     # show planned tests
    python run_atomics.py --dry-run                  # print commands, log them
    python run_atomics.py --generate                 # write runner.ps1
    python run_atomics.py --execute                  # run runner.ps1 on this host

    # Optional overrides
    --plan PATH      path to atomic_test_plan.csv (default: ../data)
    --log PATH       execution log (JSON lines, default: ../output/execution_log.jsonl)
    --art PATH       local clone of the Atomic Red Team repo (optional; if set,
                     Invoke-AtomicRedTeam uses it instead of downloading atomics)
"""

import argparse
import csv
import json
import platform
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

DEFAULT_PLAN = Path(__file__).resolve().parent.parent / "data" / "atomic_test_plan.csv"
DEFAULT_LOG = Path(__file__).resolve().parent.parent / "output" / "execution_log.jsonl"
RUNNER_NAME = "runner.ps1"


def load_plan(plan_path):
    """Read the atomic test plan CSV."""
    tests = []
    with open(plan_path, "r", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            tests.append(row)
    return tests


def log_event(log_path, event):
    """Append one JSON line to the execution log."""
    log_path.parent.mkdir(parents=True, exist_ok=True)
    event["timestamp"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    with open(log_path, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(event) + "\n")


def ps_quote(value):
    """Quote a string for safe PowerShell single-quoted literals."""
    return "'" + str(value).replace("'", "''") + "'"


def build_runner(tests, log_path, art_repo=None):
    """Generate the PowerShell runner used by --execute mode.

    Test GUIDs are resolved at runtime by name pattern against the local
    Atomic Red Team atomics folder, so the runner does not depend on test
    numbering that may shift between ART releases.
    """
    art_line = "$AtomicFolder = ''  # Invoke-AtomicRedTeam downloads atomics here\n"
    if art_repo:
        art_line = f"$AtomicFolder = {ps_quote(str(art_repo / 'atomics'))}\n"

    blocks = [
        "# runner.ps1 - generated by run_atomics.py, do not edit by hand",
        "# Requires: PowerShell 5.1+, internet access for Invoke-AtomicRedTeam",
        "Set-StrictMode -Version Latest",
        "if (-not (Get-Module Invoke-AtomicRedTeam -ListAvailable)) {",
        "    Install-Module -Name Invoke-AtomicRedTeam -Force -Scope CurrentUser",
        "}",
        "Import-Module Invoke-AtomicRedTeam -Force",
        art_line,
        "$results = @()",
    ]

    for t in tests:
        var = "T" + t["technique_id"].replace("-", "_").replace(".", "_")
        prereq_block = (
            "    Invoke-AtomicTest -TNN %s -TestGuids $match.attack_technique_guid `\n"
            "        -AtomicFolder $AtomicFolder -GetPrereqs -InputArgs %s\n" % (t["technique_id"], ps_quote(t["input_args"]))
        ) if t["prereq"] == "yes" else ""
        block = f"""
# ---- {t['technique_id']} | {t['test_name']} ----
${var} = {{
    $yaml = Join-Path (Join-Path $AtomicFolder "{t['technique_id']}") "{t['technique_id']}.yaml"
    $tech = Get-AtomicTechnique -Path $yaml
    $match = $tech.atomic_tests | Where-Object {{ $_.name -like {ps_quote(t['test_name_hint'])} }} |
        Select-Object -First 1
    if (-not $match) {{
        Write-Warning "No atomic test matching {t['test_name_hint']} found for {t['technique_id']}"
        return
    }}
    Write-Host "==> Running {t['technique_id']}: $($match.name)"
{prereq_block}    Invoke-AtomicTest -TNN {t['technique_id']} -TestGuids $match.attack_technique_guid `
        -AtomicFolder $AtomicFolder -InputArgs {ps_quote(t['input_args'])} -ExecutionLogPath {ps_quote(str(log_path))}
    [pscustomobject]@{{
        technique = "{t['technique_id']}"
        test      = $match.name
        finished  = (Get-Date).ToString('o')
    }}
}}
$results += ${var}
"""
        blocks.append(block)

    blocks.append(
        "$results | Format-Table -AutoSize\n"
        f"Write-Host 'Execution log: {log_path}'"
    )
    return "\n".join(blocks)


def main():
    parser = argparse.ArgumentParser(description="Run the Week 9 AD atomic tests.")
    parser.add_argument("--plan", type=Path, default=DEFAULT_PLAN)
    parser.add_argument("--log", type=Path, default=DEFAULT_LOG)
    parser.add_argument("--art", type=Path, default=None,
                        help="local Atomic Red Team repo path (optional)")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--list", action="store_true", help="show the test plan")
    mode.add_argument("--dry-run", action="store_true", help="print commands only")
    mode.add_argument("--generate", action="store_true", help="write runner.ps1")
    mode.add_argument("--execute", action="store_true", help="run runner.ps1")
    parser.add_argument("--lab-confirmed", action="store_true",
                        help="required with --execute: confirms this is your isolated lab")
    args = parser.parse_args()

    tests = load_plan(args.plan)

    if args.list:
        print(f"{'Test':<4} {'Technique':<11} {'Tactic':<22} Test name")
        print("-" * 90)
        for t in tests:
            print(f"{t['test_id']:<4} {t['technique_id']:<11} {t['tactic']:<22} {t['test_name']}")
        print(f"\nPlan total: {len(tests)} tests. Log file: {args.log}")
        return 0

    if args.dry_run:
        print("DRY RUN - nothing is executed. Commands that --execute would run:\n")
        for t in tests:
            print(f"[{t['test_id']}] {t['technique_id']} - {t['test_name']}")
            print(f"  prereq : {t['prereq']}")
            print(f"  command: {t['manual_command']}")
            if t.get("cleanup_command"):
                print(f"  cleanup: {t['cleanup_command']}")
            print()
            log_event(args.log, {
                "technique_id": t["technique_id"],
                "test_name": t["test_name"],
                "mode": "dry-run",
                "status": "planned",
                "host": platform.node(),
            })
        print(f"Planned events appended to {args.log}")
        return 0

    if args.generate:
        runner = build_runner(tests, args.log, args.art)
        out = Path(__file__).resolve().parent / RUNNER_NAME
        out.write_text(runner, encoding="utf-8")
        print(f"Runner written: {out}")
        print("Next: powershell -ExecutionPolicy Bypass -File runner.ps1")
        return 0

    if args.execute:
        if not args.lab_confirmed:
            print("REFUSING to run: attack techniques will be executed.")
            print("Re-run with --lab-confirmed if this is your isolated lab machine.")
            return 2
        runner = Path(__file__).resolve().parent / RUNNER_NAME
        if not runner.exists():
            print("runner.ps1 not found - run with --generate first.")
            return 1
        powershell = "powershell.exe" if platform.system() == "Windows" else "pwsh"
        result = subprocess.run(
            [powershell, "-ExecutionPolicy", "Bypass", "-File", str(runner)],
            check=False,
        )
        print(f"Exit code: {result.returncode}. Log: {args.log}")
        return result.returncode

    return 0


if __name__ == "__main__":
    sys.exit(main())
